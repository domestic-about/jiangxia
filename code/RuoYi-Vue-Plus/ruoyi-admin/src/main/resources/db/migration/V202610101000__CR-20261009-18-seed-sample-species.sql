UPDATE t_lqg_sample s
   SET species = v.species
  FROM (VALUES
        (9000001001, 'SJ90000001', '人'),
        (9000001002, 'SJ90000002', '人'),
        (9000001003, 'SJ90000003', '人'),
        (9000001004, 'SJ90000004', '移植猪'),
        (9000001005, 'SJ90000005', '鼠兔'),
        (9000001006, 'SJ90000006', '鸡'),
        (9000001008, 'SJ90000008', '移植猪'),
        (9000001009, 'SJ90000009', '鼠兔'),
        (9000001010, 'SJ90000010', '鸡')
       ) AS v(id, submit_no, species)
 WHERE s.id = v.id
   AND s.submit_no = v.submit_no
   AND s.species IS NULL;
